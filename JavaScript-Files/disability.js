let currentLanguage = localStorage.getItem('language') || 'en';

function updateLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    
    // Update language select dropdowns
    document.querySelectorAll('.language-selector').forEach(select => {
        select.value = lang;
    });
    
    // Update page title
    const pageTitle = document.querySelector('title[data-i18n]');
    if (pageTitle && translations[lang] && translations[lang][pageTitle.getAttribute('data-i18n')]) {
        pageTitle.textContent = translations[lang][pageTitle.getAttribute('data-i18n')];
    }
    
    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        
        if (translations[lang] && translations[lang][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                if (element.hasAttribute('placeholder')) {
                    element.placeholder = translations[lang][key];
                } else if (element.hasAttribute('data-placeholder')) {
                    element.setAttribute('placeholder', translations[lang][key]);
                }
            } else if (element.tagName === 'IMG') {
                element.alt = translations[lang][key];
            } else if (element.tagName === 'OPTION') {
                element.textContent = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
    
    // Update html lang attribute
    document.documentElement.lang = lang;
}

// Initialize on load
document.addEventListener('DOMContentLoaded', function() {
    updateLanguage(currentLanguage);
    
    // Add event listeners to language selectors
    document.querySelectorAll('.language-selector').forEach(select => {
        select.value = currentLanguage;
        select.addEventListener('change', function() {
            updateLanguage(this.value);
        });
    });
});
