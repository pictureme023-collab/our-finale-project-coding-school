let currentLanguage = localStorage.getItem('language') || 'en';

// Function to update language
function updateLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    
    // Update language select dropdowns
    document.querySelectorAll('.language-selector').forEach(select => {
        select.value = lang;
    });
    
    // Update page title
    const pageTitle = document.querySelector('title[data-i18n="health-education-page-title"]');
    if (pageTitle && healthEducationTranslations[lang] && healthEducationTranslations[lang]['health-education-page-title']) {
        pageTitle.textContent = healthEducationTranslations[lang]['health-education-page-title'];
    }
    
    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        
        if (healthEducationTranslations[lang] && healthEducationTranslations[lang][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                if (element.hasAttribute('data-i18n-placeholder')) {
                    const placeholderKey = element.getAttribute('data-i18n-placeholder');
                    if (healthEducationTranslations[lang][placeholderKey]) {
                        element.placeholder = healthEducationTranslations[lang][placeholderKey];
                    }
                } else if (element.hasAttribute('placeholder')) {
                    element.setAttribute('placeholder', healthEducationTranslations[lang][key]);
                }
            } else if (element.tagName === 'IMG') {
                element.alt = healthEducationTranslations[lang][key];
            } else if (element.tagName === 'OPTION') {
                element.textContent = healthEducationTranslations[lang][key];
            } else {
                element.textContent = healthEducationTranslations[lang][key];
            }
        }
    });
    
    // Update html lang attribute
    document.documentElement.lang = lang;
}

// Mobile menu functionality
function setupMobileMenu() {
    const mobileMenuButton = document.getElementById('mobile-menu-button');
    const mobileMenu = document.getElementById('mobile-menu');
    const mobileServicesToggle = document.getElementById('mobile-services-toggle');
    const mobileServicesMenu = document.getElementById('mobile-services-menu');

    if (mobileMenuButton && mobileMenu) {
        mobileMenuButton.addEventListener('click', function() {
            mobileMenu.classList.toggle('hidden');
        });
    }

    if (mobileServicesToggle && mobileServicesMenu) {
        mobileServicesToggle.addEventListener('click', function() {
            mobileServicesMenu.classList.toggle('hidden');
        });
    }
}

// Utility function to show notifications
function showNotification(message, type = 'info') {
    const notification = document.createElement('div');
    notification.className = `fixed top-4 right-4 p-4 rounded-lg shadow-lg z-50 ${
        type === 'success' ? 'bg-green-500 text-white' :
        type === 'error' ? 'bg-red-500 text-white' :
        'bg-blue-500 text-white'
    }`;
    notification.textContent = message;
    
    document.body.appendChild(notification);
    
    setTimeout(() => {
        notification.remove();
    }, 5000);
}

// Initialize everything
document.addEventListener('DOMContentLoaded', function() {
    console.log("Health Education page loaded");
    
    // Initialize language
    updateLanguage(currentLanguage);
    
    // Add event listeners to language selectors
    document.querySelectorAll('.language-selector').forEach(select => {
        select.value = currentLanguage;
        select.addEventListener('change', function() {
            updateLanguage(this.value);
        });
    });
    
    // Setup mobile menu
    setupMobileMenu();
    
    // Login/Signup buttons (placeholder functionality)
    const loginButtons = [
        document.getElementById('desktop-login-btn'),
        document.getElementById('mobile-login-btn'),
        document.getElementById('login-btn')
    ];

    const signupButtons = [
        document.getElementById('desktop-signup-btn'),
        document.getElementById('mobile-signup-btn'),
        document.getElementById('signup-btn')
    ];

    loginButtons.forEach(btn => {
        if (btn) {
            btn.addEventListener('click', function() {
                showNotification(
                    currentLanguage === 'rw'
                        ? 'Ubushobozi bwo kwinjira buri hano.'
                        : 'Login functionality would be implemented here.',
                    'info'
                );
            });
        }
    });

    signupButtons.forEach(btn => {
        if (btn) {
            btn.addEventListener('click', function() {
                showNotification(
                    currentLanguage === 'rw'
                        ? 'Ubushobozi bwo kwiyandika buri hano.'
                        : 'Signup functionality would be implemented here.',
                    'info'
                );
            });
        }
    });
    
    // Add smooth scrolling for anchor links
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            const href = this.getAttribute('href');
            if (href !== '#') {
                e.preventDefault();
                const targetElement = document.querySelector(href);
                if (targetElement) {
                    targetElement.scrollIntoView({
                        behavior: 'smooth',
                        block: 'start'
                    });
                }
            }
        });
    });
});

