let currentLanguage = localStorage.getItem('language') || 'en';

// Function to update language
function updateLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    
    // Update language select dropdowns
    document.querySelectorAll('select[data-i18n="language-select"]').forEach(select => {
        select.value = lang;
    });
    
    // Update page title
    const pageTitle = document.querySelector('title[data-i18n="emergency-page-title"]');
    if (pageTitle && emergencyTranslations[lang] && emergencyTranslations[lang]['emergency-page-title']) {
        pageTitle.textContent = emergencyTranslations[lang]['emergency-page-title'];
    }
    
    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        
        if (emergencyTranslations[lang] && emergencyTranslations[lang][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                if (element.hasAttribute('data-placeholder')) {
                    element.placeholder = emergencyTranslations[lang][key];
                }
            } else if (element.tagName === 'IMG') {
                if (element.hasAttribute('data-alt')) {
                    element.alt = emergencyTranslations[lang][key];
                }
            } else if (element.tagName === 'OPTION') {
                element.textContent = emergencyTranslations[lang][key];
            } else {
                element.textContent = emergencyTranslations[lang][key];
            }
        }
    });
    
    // Update html lang attribute
    document.documentElement.lang = lang;
}

// Utility function to show notifications
function showNotification(message, type = 'info') {
    // Remove existing notifications
    const existingNotifications = document.querySelectorAll('.notification');
    existingNotifications.forEach(notification => notification.remove());
    
    // Create new notification
    const notification = document.createElement('div');
    notification.className = `fixed top-4 right-4 p-4 rounded-lg shadow-lg z-50 ${
        type === 'success' ? 'bg-green-500 text-white' :
        type === 'error' ? 'bg-red-500 text-white' :
        'bg-blue-500 text-white'
    }`;
    notification.textContent = message;
    
    document.body.appendChild(notification);
    
    setTimeout(() => {
        notification.remove();
    }, 5000);
}

